try:
    a = float(input("Введіть перше число: "))
    b = float(input("Введіть друге число: "))
    op = input("Операція (+, -, *, /): ").strip()

    if op == "+":
        result = a + b
    elif op == "-":
        result = a - b
    elif op == "*":
        result = a * b
    elif op == "/":
        result = a / b
    else:
        raise ValueError("невідома операція")

except ValueError:
    print("Помилка: потрібно вводити тільки числа або оберіть правильну операцію (+, -, *, /).")

except ZeroDivisionError:
    print("Помилка: на нуль ділити не можна.")

else:
    print(f"Результат: {a} {op} {b} = {result}")
    print("Операція виконана успішно.")

finally:
    print("Роботу калькулятора завершено.")


# try / except — це спосіб обробити помилку, не зупиняючи програму.
#   Код у блоці try виконується звично. Якщо щось іде не так —
#   Python "кидає виняток" і стрибає у відповідний блок except.
#
# ValueError      — виникає коли тип правильний, але значення — ні.
#                   Наприклад: float("привіт") — рядок є, але не число.
# ZeroDivisionError — виникає при діленні будь-якого числа на 0: 5 / 0.
#
# else   — виконується тільки якщо в try не було жодної помилки.
#          Зручно відокремити "успішний результат" від обробки помилок.
# finally — виконується ЗАВЖДИ: і після успіху, і після помилки.
#           Використовується для "прибирання" — закрити файл, з'єднання тощо.