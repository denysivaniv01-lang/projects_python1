students = ["Анна", "Максим", "Олег", "Ірина", "Софія"]

print("Список студентів:")
for i, name in enumerate(students):
    print(f"  {i} — {name}")

try:
    index = int(input("\nВведіть індекс студента: "))
    student = students[index]

except ValueError:
    print("Помилка: індекс має бути числом.")

except IndexError:
    print("Помилка: студента з таким індексом немає.")

else:
    print(f"Обраний студент: {student}")
    print("Пошук виконано успішно.")

finally:
    print("Перевірку списку завершено.")


# Індекс — це порядковий номер елемента у списку.
#   В Python індексація починається з 0, тобто перший елемент — students[0].
#
# IndexError — виникає коли звертаєшся до індексу, якого не існує.
#   Наприклад, у списку з 5 елементів students[10] кине IndexError.
#
# try-except дозволяє програмі не "впасти" від помилки, а обробити її
#   і продовжити роботу — або вивести зрозуміле повідомлення користувачу.