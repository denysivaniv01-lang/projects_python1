while True:
    try:
        age = int(input("Введіть ваш вік: "))
    except ValueError:
        print("Помилка: вік потрібно вводити числом.")
        continue

    if not (1 <= age <= 120):
        print("Помилка: вік має бути від 1 до 120.")
        continue

    print(f"Вік прийнято: {age}")
    break

print("Дані збережено.")


# int("500") → 500 без жодної помилки, бо "500" — це коректний рядок для числа.
#   Але 500 років людині не буває — це вже логічна помилка, а не технічна.
#   Саме тому її перевіряємо через if, а не через except.
#
# ValueError  — системна помилка: Python не знає як перетворити "привіт" на int.
# Логічна помилка — число правильне технічно, але не має сенсу в реальності.
#   Python про це не знає, тому перевірка лежить на нас.
#
# while + try-except — класична зв'язка для надійного введення даних:
#   цикл гарантує повтор, try-except ловить технічні помилки, if — логічні.
#   Програма просто не рухається далі, поки не отримає нормальні дані.