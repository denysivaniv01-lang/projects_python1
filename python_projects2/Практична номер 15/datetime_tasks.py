from datetime import datetime, date

# --- 1. Поточна дата у красивому форматі ---

months = {
    1: "січня",   2: "лютого",  3: "березня",
    4: "квітня",  5: "травня",  6: "червня",
    7: "липня",   8: "серпня",  9: "вересня",
    10: "жовтня", 11: "листопада", 12: "грудня",
}

now = datetime.now()

print(f"Сьогодні: {now.day} {months[now.month]} {now.year} року")
print(f"Поточний час: {now.strftime('%H:%M')}")


# --- 2. Кількість днів до події ---

raw = input("\nВведіть дату події (ДД.ММ.РРРР): ")
event = datetime.strptime(raw, "%d.%m.%Y").date()
today = date.today()

delta = event - today

if delta.days > 0:
    print(f"До події залишилось: {delta.days} днів.")
elif delta.days < 0:
    print(f"Подія була {abs(delta.days)} днів тому.")
else:
    print("Подія — сьогодні!")

# "15.06.2026" — просто текст, незрозумілий більшості людей без контексту.
#   "15 червня 2026 року" читається природньо рідною мовою.
#   Python не має вбудованої української локалізації, тому місяці прописуємо
#   вручну у словнику — це і є базова локалізація.
#
# timedelta — об'єкт що представляє різницю між двома датами або часом.
#   Коли віднімаємо одну дату від іншої (event - today), Python повертає
#   саме timedelta. З нього беремо .days — ціле число днів різниці.
#   Може бути від'ємним, якщо перша дата раніша за другу.
