import my_tools

print(my_tools.greet("Анна"))
print(f"Квадрат числа: {my_tools.square(5)}")
print(f"Число парне: {my_tools.is_even(4)}")
print(f"Ім'я після форматування: {my_tools.format_name('максим')}")


# Коли пишеш import my_tools, Python шукає файл my_tools.py спочатку
#   у тій самій папці де лежить main.py, потім у стандартних системних
#   директоріях. Тому обидва файли мають бути поруч.
#
# import my_tools          — імпортує весь модуль. До функцій звертаємось
#                            через крапку: my_tools.greet("Анна").
#                            Одразу видно звідки функція — зручно в більших проектах.
#
# from my_tools import greet — імпортує тільки одну функцію напряму.
#                            Можна писати просто greet("Анна") без префіксу.
#                            Зручно коли використовуєш функцію часто.